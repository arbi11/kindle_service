/* Three-panel interactions against connection_ui_server.py; synthetic services only. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async()=>{
  const runtimePath = process.argv[2];
  if (!runtimePath) throw new Error('Pass a fresh connection_ui_server runtime.json');
  const runtime = JSON.parse(fs.readFileSync(runtimePath,'utf8'));
  const output = path.join(path.dirname(runtimePath),'screenshots');
  fs.mkdirSync(output,{recursive:true});
  const browser = await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE || '/usr/bin/google-chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1360,height:900}});
  const errors = [], external = [];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(!request.url().startsWith('http://127.0.0.1:')&&!request.url().startsWith('data:')) external.push(request.url());});
  const rail = page.locator('.connection-rail');
  const panel = id=>rail.locator('[data-rail-connection="'+id+'"]');
  const toggle = name=>rail.getByRole('button',{name:name+' settings',exact:true});
  const nav = async name=>{
    await page.locator('.primary-nav').getByRole('button',{name,exact:true}).click();
    await page.locator('.primary-nav [aria-current="page"][aria-label="'+name+'"]').waitFor();
  };
  const filter = async name=>{
    await page.locator('.connection-nav').getByRole('button',{name,exact:true}).click();
    await page.locator('.connection-nav [aria-pressed="true"][aria-label="'+name+'"]').waitFor();
  };
  const waitDone = async kind=>page.waitForFunction(async kind=>{
    const data=await(await fetch('/api/bootstrap')).json();
    return data.jobs.some(job=>job.kind===kind&&job.status==='done')&&!data.jobs.some(job=>['queued','running'].includes(job.status));
  },kind,{timeout:30000});
  const shot = name=>page.screenshot({path:path.join(output,name+'.png'),fullPage:true});
  try {
    await page.goto(`http://127.0.0.1:${runtime.port}/?session=${runtime.token}`);
    await page.getByRole('heading',{name:'Readers Digest',exact:true}).waitFor();
    assert.deepEqual(await page.locator('.primary-nav button').evaluateAll(buttons=>buttons.map(b=>b.getAttribute('aria-label'))),['Today','Library','Sources','Delivery','Settings']);
    assert.equal(await rail.locator('.connection-toggle').count(),3);
    assert.equal(await rail.locator('.connection-toggle[aria-expanded="true"]').count(),0);
    assert.equal(await page.locator('.rail-card,.quote-card').count(),0);
    await shot('01-reading-room');
    await toggle('YouTube').press('Enter');
    await panel('youtube').getByLabel('Channel URL or @handle',{exact:true}).fill('@draft-channel');
    await page.locator('.digest-title').first().click();
    await page.locator('.article-preview:not([hidden])').waitFor();
    assert.equal(await panel('youtube').getByLabel('Channel URL or @handle',{exact:true}).inputValue(),'@draft-channel');
    await toggle('Raindrop').click();
    assert.equal(await toggle('YouTube').getAttribute('aria-expanded'),'false');
    assert.equal(await rail.locator('.connection-toggle[aria-expanded="true"]').count(),1);
    await panel('raindrop').getByRole('button',{name:'Follow collection',exact:true}).click();
    await panel('raindrop').locator('.modal-error').waitFor();
    assert.equal(await page.locator('dialog[open]').count(),0);
    await panel('raindrop').getByLabel('Raindrop token',{exact:true}).fill('synthetic-panel-token');
    await panel('raindrop').getByLabel('Filter by tags (optional)',{exact:true}).fill('science');
    await toggle('YouTube').click();
    assert.equal(await panel('youtube').getByLabel('Channel URL or @handle',{exact:true}).inputValue(),'@draft-channel');
    await toggle('Raindrop').click();
    assert.equal(await panel('raindrop').getByLabel('Raindrop token',{exact:true}).inputValue(),'synthetic-panel-token');
    await panel('raindrop').getByRole('button',{name:'Check connection & load collections',exact:true}).click();
    await waitDone('test_raindrop');
    await panel('raindrop').locator('select[name="collection_id"] option[value="3"]').waitFor({state:'attached'});
    await panel('raindrop').getByLabel('Collection',{exact:true}).selectOption('3');
    assert.equal(await panel('raindrop').getByLabel('Display name',{exact:true}).inputValue(),'Science');
    await panel('raindrop').getByRole('button',{name:'Follow collection',exact:true}).click();
    await panel('raindrop').getByRole('switch',{name:'Pause Science',exact:true}).waitFor();
    assert.equal(await panel('raindrop').getByLabel('Raindrop token',{exact:true}).inputValue(),'');
    await panel('raindrop').locator('[data-action="fetch-source"]').click();
    await panel('raindrop').getByLabel('Display name',{exact:true}).fill('Unsaved new collection');
    await waitDone('prepare');
    await page.waitForFunction(()=>document.querySelectorAll('.digest-article').length===1);
    assert.equal(await panel('raindrop').getByLabel('Display name',{exact:true}).inputValue(),'Unsaved new collection');
    await filter('Raindrop');
    await nav('Settings');
    await page.getByLabel('Your interests',{exact:true}).fill('Keep these unsaved preferences');
    await toggle('YouTube').click();
    await panel('youtube').getByLabel('Channel URL or @handle',{exact:true}).fill('@sample');
    await panel('youtube').getByRole('button',{name:'Follow channel',exact:true}).click();
    await waitDone('add_youtube');
    await panel('youtube').getByRole('switch',{name:'Pause Sample channel',exact:true}).waitFor();
    assert.equal(await page.getByLabel('Your interests',{exact:true}).inputValue(),'Keep these unsaved preferences');
    await toggle('Freedium').click();
    await panel('freedium').getByRole('button',{name:'Connect Freedium',exact:true}).click();
    await panel('freedium').getByRole('switch',{name:/Pause/}).waitFor();
    await panel('freedium').locator('[data-action="fetch-source"]').click();
    await page.waitForFunction(async()=>{
      const data=await(await fetch('/api/items')).json();
      return data.items.some(item=>item.connection_id==='freedium');
    });
    await page.locator('.connection-nav [data-connection="freedium"]').waitFor();
    assert.equal(await page.getByLabel('Your interests',{exact:true}).inputValue(),'Keep these unsaved preferences');
    await panel('freedium').getByRole('switch').click();
    await panel('freedium').getByRole('switch',{name:/Resume/}).waitFor();
    assert.equal(await panel('freedium').locator('[data-action="fetch-source"]').isDisabled(),true);
    await panel('freedium').getByRole('switch').click();
    await panel('freedium').getByRole('switch',{name:/Pause/}).waitFor();
    await nav('Today');await filter('All connections');
    await page.waitForFunction(()=>document.querySelectorAll('.digest-article').length===2);
    await shot('02-freedium-settings');
    await filter('Freedium');
    await page.waitForFunction(()=>document.querySelectorAll('.digest-article').length===1);
    assert.equal(await toggle('Freedium').getAttribute('aria-expanded'),'true');
    await nav('Library');await page.locator('.reading-card').waitFor();
    assert.equal(await page.locator('.reading-card').count(),1);
    await page.locator('.reading-card').click();await page.locator('.prose').waitFor();
    assert.equal(await page.locator('.connection-rail').count(),0);
    await page.getByRole('button',{name:'Back to reading list',exact:true}).click();
    await rail.waitFor();assert.equal(await toggle('Freedium').getAttribute('aria-expanded'),'true');
    await panel('freedium').locator('[data-action="remove-source"]').click();
    await page.getByRole('button',{name:'Remove source',exact:true}).click();
    await panel('freedium').getByRole('button',{name:'Connect Freedium',exact:true}).waitFor();
    assert.equal(await page.locator('.reading-card').count(),1);
    await nav('Today');await filter('All connections');
    await toggle('Raindrop').click();await shot('03-raindrop-settings');
    for(const width of [1360,1000,900]) {
      await page.setViewportSize({width,height:800});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
      assert.equal(await rail.isVisible(),true);
      const bounds=await rail.boundingBox();assert.ok(Math.abs(bounds.x+bounds.width-width)<2,'Right panel reaches the window edge');
    }
    await shot('04-small-laptop');
    await toggle('Raindrop').press('Space');
    assert.equal(await toggle('Raindrop').getAttribute('aria-expanded'),'false');
    const state=await page.evaluate(async()=>await(await fetch('/api/bootstrap')).json());
    assert.equal(state.deliveries.length,0);assert.equal(state.settings.auto_send,false);assert.equal(state.settings.schedule_enabled,false);
    assert.ok(!JSON.stringify(state).includes('synthetic-panel-token'));
    assert.equal(await page.evaluate(()=>JSON.stringify(localStorage).includes('synthetic-panel-token')),false);
    assert.equal(errors.length,0,errors.join('\n'));assert.equal(external.length,0,external.join('\n'));
    console.log(JSON.stringify({result:'PASS',checks:['v0.1 navigation and separate story filter','right connection accordions and keyboard','inline setup errors','unsaved connection drafts','Raindrop credential and collection setup','YouTube setup','Freedium connect fetch pause resume disconnect','settings drafts survive connection jobs','feed and library connector filters','reader return','three panels at laptop sizes','secret masking and no sending'],screenshots:output}));
  } catch(error) {await shot('failure');throw error;} finally {await browser.close();}
})().catch(error=>{console.error(error.stack);process.exit(1);});
