/* Exercise the real UI/server with tests/connection_ui_server.py. No real keys or mail. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');

(async()=>{
  const runtimePath=process.argv[2];
  if(!runtimePath) throw new Error('Pass an isolated connection_ui_server runtime.json');
  const runtime=JSON.parse(fs.readFileSync(runtimePath,'utf8'));
  const output=path.join(path.dirname(runtimePath),'screenshots');fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE||'/usr/bin/google-chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1360,height:950}});
  const errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(!request.url().startsWith('http://127.0.0.1:')&&!request.url().startsWith('data:'))external.push(request.url());});
  const shot=name=>page.screenshot({path:path.join(output,name+'.png'),fullPage:true});
  const action=async name=>page.locator('[data-action="'+name+'"]').first().click();
  const manage=async()=>{await page.getByRole('button',{name:'Sources',exact:true}).click();await page.getByRole('heading',{name:'Manage connections',exact:true}).waitFor();};
  const browse=async()=>{await page.getByRole('tab',{name:'Browse connections',exact:true}).click();await page.locator('.catalogue-card').first().waitFor();};
  const card=id=>page.locator('[data-catalogue-id="'+id+'"]');
  const group=id=>page.locator('.connection-group[data-connection-id="'+id+'"]');
  const boot=()=>page.evaluate(async()=>await(await fetch('/api/bootstrap')).json());
  const waitDone=async count=>page.waitForFunction(async count=>{
    const data=await(await fetch('/api/bootstrap')).json();
    return data.jobs.filter(job=>job.kind==='prepare'&&job.status==='done').length>=count;
  },count,{timeout:30000});
  try {
    await page.goto(`http://127.0.0.1:${runtime.port}/?session=${runtime.token}`);
    await page.getByRole('heading',{name:'Readers Digest',exact:true}).waitFor();
    await manage();await page.getByRole('heading',{name:'No connections yet',exact:true}).waitFor();
    await browse();assert.equal(await page.locator('.catalogue-card').count(),3);
    assert.equal(await page.locator('.review-label').count(),3);await shot('01-browse-connections');
    await page.getByRole('tab',{name:'Browse connections',exact:true}).press('ArrowLeft');
    assert.equal(await page.getByRole('tab',{name:'Your connections',exact:true}).getAttribute('aria-selected'),'true');
    await page.getByRole('tab',{name:'Your connections',exact:true}).press('ArrowRight');
    await card('freedium').getByRole('button',{name:'Connect',exact:true}).click();
    await page.getByRole('heading',{name:'Connect Freedium',exact:true}).waitFor();
    assert.match(await page.locator('.connection-access').innerText(),/No account credentials/);
    await shot('02-freedium-setup');
    await page.getByRole('button',{name:'Connect Freedium',exact:true}).click();
    await group('freedium').waitFor();await shot('03-your-connections');
    assert.equal(await page.locator('.connection-nav [data-connection="freedium"]').count(),1);
    await group('freedium').locator('[data-action="fetch-source"]').click();
    await waitDone(1);
    await page.waitForFunction(()=>document.querySelector('.connected-source-info')?.textContent.includes('1 article'));
    let state=await boot();assert.equal(state.settings.schedule_enabled,false);assert.equal(state.settings.auto_send,false);assert.equal(state.deliveries.length,0);
    assert.equal(state.sources.find(source=>source.kind==='freedium').error,'');
    await page.getByRole('button',{name:'Freedium',exact:true}).click();
    await page.locator('.digest-title').waitFor();assert.equal(await page.locator('.digest-article').count(),1);
    await action('preview');
    assert.match(await page.locator('.preview-prose').innerText(),/\$3 million/);
    await shot('04-freedium-reading-feed');
    await action('read');await page.locator('.prose').waitFor();
    assert.match(await page.locator('.prose').innerText(),/\$2 million/);
    await action('star');await action('mark-read');await action('reader-back');
    await page.locator('.digest-article.is-read .article-preview:not([hidden])').waitFor();
    await manage();
    await group('freedium').getByRole('switch').click();
    await group('freedium').getByRole('switch',{name:/Resume/}).waitFor();
    assert.equal(await group('freedium').locator('[data-action="fetch-source"]').isDisabled(),true);
    await group('freedium').getByRole('switch').click();
    await group('freedium').getByRole('switch',{name:/Pause/}).waitFor();
    await group('freedium').locator('[data-action="fetch-source"]').click();await waitDone(2);
    await page.getByRole('button',{name:'Freedium',exact:true}).click();await page.locator('.digest-title').waitFor();
    assert.equal(await page.locator('.digest-article').count(),1);
    await manage();await group('freedium').locator('[data-action="remove-source"]').click();
    await page.getByRole('button',{name:'Remove source',exact:true}).click();
    await page.getByRole('heading',{name:'No connections yet',exact:true}).waitFor();
    await page.getByRole('button',{name:'Freedium',exact:true}).click();await page.locator('.digest-title').waitFor();
    assert.equal(await page.locator('.digest-article.is-read').count(),1);
    await manage();await browse();
    await card('youtube').getByRole('button',{name:'Connect',exact:true}).click();
    await page.getByLabel('Channel URL or @handle',{exact:true}).fill('@sample');
    await page.getByRole('button',{name:'Follow channel',exact:true}).click();
    await group('youtube').waitFor({timeout:30000});assert.match(await group('youtube').innerText(),/Sample channel/);
    await browse();await card('raindrop').getByRole('button',{name:'Connect',exact:true}).click();
    await page.getByLabel('Raindrop token',{exact:true}).fill('synthetic-ui-raindrop-token');
    await page.getByLabel('Display name',{exact:true}).fill('Sample saved articles');
    await page.getByLabel('Filter by tags (optional)',{exact:true}).fill('science');
    await page.getByRole('button',{name:'Follow collection',exact:true}).click();
    await group('raindrop').waitFor();
    await group('raindrop').locator('[data-action="fetch-source"]').click();await waitDone(3);
    await page.getByRole('button',{name:'Raindrop',exact:true}).click();await page.locator('.digest-title').waitFor();
    assert.equal(await page.locator('.digest-article').count(),1);
    assert.match(await page.locator('.digest-title').innerText(),/Saved reading fixture/);
    await page.getByRole('button',{name:'All connections',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.digest-article').length===2);
    await page.getByRole('button',{name:'Library',exact:true}).click();await page.locator('.reading-card').first().waitFor();
    await action('edition');await page.locator('.edition-summary').waitFor();
    const downloadPromise=page.waitForEvent('download');await page.getByRole('link',{name:'EPUB',exact:true}).click();
    const download=await downloadPromise;await download.saveAs(path.join(output,'connection-edition.epub'));
    assert.equal(download.suggestedFilename(),'Daily-Edition.epub');
    await page.reload();await page.locator('.digest-layout').waitFor();
    const library=await page.evaluate(async()=>await(await fetch('/api/items')).json());
    assert.equal(library.items.length,2);
    assert.equal(library.items.filter(item=>item.connection_id==='freedium'&&item.starred&&item.is_read).length,1);
    state=await boot();assert.equal(state.deliveries.length,0);assert.equal(state.settings.auto_send,false);
    assert.ok(!JSON.stringify(state).includes('synthetic-ui-raindrop-token'));
    await manage();await browse();
    for(const width of [1000,900]) {await page.setViewportSize({width,height:800});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);}
    await shot('05-small-laptop-catalogue');
    assert.equal(errors.length,0,errors.join('\n'));assert.equal(external.length,0,external.join('\n'));
    console.log(JSON.stringify({result:'PASS',checks:['catalogue and keyboard tabs','Freedium setup and fetching','inline preview and expanded reader','pause and resume','retry without duplicates','disconnect preserves reading','YouTube setup','Raindrop setup and fetching','connection filters and combined feed','EPUB export','persistent state','no secret disclosure','no real email or browser network'],screenshots:output}));
  } catch(error) {await shot('failure');throw error;} finally {await browser.close();}
})().catch(error=>{console.error(error.stack);process.exit(1);});
